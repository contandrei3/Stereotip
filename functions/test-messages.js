// node test-messages.js — quick checks for the message rules
const assert = require('assert')
const m = require('./messages')
const ev = m.messageForCreate('events', { type: 'rehearsal', date: '2026-11-26', time: '19:00', location: 'Sala Rock', by: 'mario' }, { id: 'e1' })
assert.deepStrictEqual(ev.to, ['andrei', 'mihai', 'david', 'andreeas']); console.log(ev.title, '|', ev.body)
const task = m.messageForCreate('tasks', { title: 'Bring the DI box', assignee: 'andrei', by: 'mario', due: '2026-11-28' }, { id: 't' })
assert.deepStrictEqual(task.to, ['andrei']); console.log(task.title, '|', task.body)
assert.strictEqual(m.messageForCreate('tasks', { title: 'x', assignee: 'mario', by: 'mario' }, {}), null)
const rem = m.messageForCreate('reminders', { text: 'Pay the room', for: 'all', by: 'david', date: '2026-11-25', time: '18:00' }, { id: 'r' })
assert.ok(!rem.to.includes('david')); console.log(rem.title, '|', rem.body)
const cm = m.messageForCreate('comments', { postId: 'p', text: 'Nice', by: 'david' }, { post: { author: 'mario' }, commenters: ['david', 'mihai'] })
assert.deepStrictEqual(cm.to.sort(), ['mario', 'mihai']); console.log(cm.title, '|', cm.body)
const ab = m.messageForCreate('absences', { member: 'andrei', from: '2026-12-12', to: '2026-12-13', reason: 'Not in the city', by: 'andrei' }, { id: 'a' })
assert.ok(!ab.to.includes('andrei')); console.log(ab.title, '|', ab.body)
const ob = m.messageForCreate('observations', { text: 'Bridge messy', by: 'mihai', eventId: 'e', songId: 's' }, { event: { date: '2026-11-25' }, song: { title: 'Low Battery' } })
console.log(ob.title, '|', ob.body)
assert.strictEqual(m.messageForCreate('seen', {}, {}), null)
// Bucharest is UTC+2 in winter, UTC+3 in summer
assert.strictEqual(new Date(m.localToUtc('2026-11-26', '19:00')).toISOString(), '2026-11-26T17:00:00.000Z')
assert.strictEqual(new Date(m.localToUtc('2026-07-10', '19:00')).toISOString(), '2026-07-10T16:00:00.000Z')
const up = m.messageForUpcomingEvent({ type: 'rehearsal', date: '2026-11-26', time: '19:00', location: 'Sala Rock' }, 'e', ['Low Battery', 'Static Hearts'])
console.log(up.title, '|', up.body)
console.log('all message tests passed')
